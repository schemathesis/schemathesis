def _missing_content_type(fixed):
    response = jsonify({"id": 1})
    if not fixed:
        del response.headers["Content-Type"]
    return response


def _undefined_content_type(fixed):
    return jsonify({"id": 1}) if fixed else Response('{"id": 1}', content_type="text/plain")


def _malformed_media_type(fixed):
    return jsonify({"id": 1}) if fixed else Response('{"id": 1}', headers={"Content-Type": "invalid"})


def _missing_headers(fixed):
    return jsonify({"id": 1}), 200, {"X-Rate": "1"} if fixed else {}


def _schema_violation(fixed):
    return jsonify({"id": 1 if fixed else "x"})


def _malformed_json(fixed):
    return Response('{"id": 1}' if fixed else "{", content_type="application/json")


def _slow(fixed):
    if not fixed:
        time.sleep(1.5)
    return jsonify({"id": 1})


@pytest.mark.parametrize(
    ("respond", "options", "symptom"),
    [
        (
            _missing_content_type,
            ("--checks=content_type_conformance",),
            "    assert 'Content-Type' not in response.headers\n",
        ),
        (
            _undefined_content_type,
            ("--checks=content_type_conformance",),
            "    assert response.headers['Content-Type'] == 'text/plain'\n",
        ),
        (
            _malformed_media_type,
            ("--checks=content_type_conformance",),
            "    assert response.headers['Content-Type'] == 'invalid'\n",
        ),
        (_missing_headers, ("--checks=response_headers_conformance",), "    assert 'X-Rate' not in response.headers\n"),
        (_schema_violation, ("--checks=response_schema_conformance",), "    assert response.json()['id'] == 'x'\n"),
        (
            _malformed_json,
            ("--checks=response_schema_conformance",),
            "    with pytest.raises(ValueError):\n        response.json()\n",
        ),
        (
            _slow,
            ("--checks=not_a_server_error", "--max-response-time=1.0"),
            "    assert response.elapsed.total_seconds() > 1.0\n",
        ),
    ],
    ids=[
        "missing-content-type",
        "undefined-content-type",
        "malformed-media-type",
        "missing-headers",
        "schema-violation",
        "malformed-json",
        "response-time",
    ],
)
def test_symptom_is_asserted_until_fixed(ctx, cli, tmp_path, pytester, respond, options, symptom):
    app, _ = ctx.openapi.make_flask_app(
        {
            "/items": {
                "get": {
                    "responses": {
                        "200": {
                            "description": "OK",
                            "headers": {"X-Rate": {"required": True, "schema": {"type": "string"}}},
                            "content": {
                                "application/json": {
                                    "schema": {
                                        "type": "object",
                                        # `"x"` breaks both keywords, yet the generated test asserts it once.
                                        "properties": {"id": {"type": "integer", "enum": [1]}},
                                        "required": ["id"],
                                    }
                                }
                            },
                        }
                    }
                }
            }
        }
    )
    state = {"fixed": False}

    @app.route("/items")
    def items():
        return respond(state["fixed"])

    path = tmp_path / "test_regressions.py"
    cli.run_openapi_app(
        app,
        f"--report-pytest-path={path}",
        "--max-examples=1",
        "--phases=fuzzing",
        *options,
    )

    content = path.read_text(encoding="utf-8")
    assert content.split("assert response.status_code == 200\n")[1] == symptom
    pytester.makepyfile(test_regressions=content)
    pytester.runpytest().assert_outcomes(passed=1)
    state["fixed"] = True
    pytester.runpytest().assert_outcomes(failed=1)


