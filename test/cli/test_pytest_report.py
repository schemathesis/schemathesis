import re

from _pytest.main import ExitCode
from flask import jsonify, request
from requests.utils import DEFAULT_ACCEPT_ENCODING

from schemathesis.core.version import SCHEMATHESIS_VERSION


def test_server_error_becomes_passing_test(ctx, cli, tmp_path, pytester):
    api = ctx.openapi.apps.failure()
    path = tmp_path / "test_regressions.py"

    cli.run_and_assert(
        api.schema_url,
        f"--report-pytest-path={path}",
        "--max-examples=1",
        "--phases=fuzzing",
        "--checks=not_a_server_error",
        exit_code=ExitCode.TESTS_FAILED,
    )

    content = path.read_text(encoding="utf-8")
    [case_id] = re.findall(r"Test Case ID: (\w+)", content)
    assert (
        content
        == f"""# Generated by Schemathesis {SCHEMATHESIS_VERSION} from {api.schema_url}
# Each test asserts the status code observed during the run, so it fails once the behavior changes.
# Sensitive values are replaced with `[Filtered]`; fill them in before running.
import requests


# GET /api/failure
# 1. Test Case ID: {case_id}
#
# - Server error
#
# [500] Internal Server Error:
#
#     `500: Internal Server Error`
def test_get_api_failure_{case_id}():
    response = requests.request(
        'GET',
        '{api.base_url}/api/failure',
        headers={{'User-Agent': 'schemathesis/{SCHEMATHESIS_VERSION}', 'Accept-Encoding': '{DEFAULT_ACCEPT_ENCODING}', 'Accept': '*/*', 'Connection': 'keep-alive', 'X-Schemathesis-TestCaseId': '{case_id}'}},
    )
    assert response.status_code == 500
"""
    )
    pytester.makepyfile(test_regressions=content)
    pytester.runpytest().assert_outcomes(passed=1)


def test_stateful_failure_replays_the_chain(ctx, cli, tmp_path, pytester):
    app, _ = ctx.openapi.make_flask_app(
        {
            "/items": {
                "post": {
                    "responses": {
                        "201": {
                            "description": "Created",
                            "content": {
                                "application/json": {
                                    "schema": {
                                        "type": "object",
                                        "properties": {"id": {"type": "integer"}},
                                        "required": ["id"],
                                    }
                                }
                            },
                            "links": {
                                "GetItem": {"operationId": "getItem", "parameters": {"id": "$response.body#/id"}}
                            },
                        }
                    }
                }
            },
            "/items/{id}": {
                "get": {
                    "operationId": "getItem",
                    "parameters": [{"name": "id", "in": "path", "required": True, "schema": {"type": "integer"}}],
                    "responses": {"200": {"description": "OK"}},
                }
            },
        }
    )

    @app.route("/items", methods=["POST"])
    def create_item():
        return jsonify({"id": 1}), 201

    @app.route("/items/<int:item_id>")
    def get_item(item_id):
        return jsonify({}), 500

    path = tmp_path / "test_regressions.py"
    cli.run_openapi_app(
        app, f"--report-pytest-path={path}", "--max-examples=5", "--phases=stateful", "--checks=not_a_server_error"
    )

    content = path.read_text(encoding="utf-8")
    assert re.findall(r"requests.request\(\s*'(\w+)'", content) == ["POST", "GET"]
    assert re.findall(r"assert response.status_code == (\d+)", content) == ["201", "500"]
    assert "def test_get_items_id_" in content
    pytester.makepyfile(test_regressions=content)
    pytester.runpytest().assert_outcomes(passed=1)


def test_binary_body_round_trips(ctx, cli, tmp_path, pytester):
    app, _ = ctx.openapi.make_flask_app(
        {
            "/upload": {
                "post": {
                    "requestBody": {
                        "required": True,
                        "content": {"application/octet-stream": {"schema": {"type": "string", "format": "binary"}}},
                    },
                    "responses": {"200": {"description": "OK"}},
                }
            }
        }
    )

    @app.route("/upload", methods=["POST"])
    def upload():
        try:
            request.get_data().decode("utf-8")
        except UnicodeDecodeError:
            return "", 500
        return "", 200

    path = tmp_path / "test_regressions.py"
    cli.run_openapi_app(
        app, f"--report-pytest-path={path}", "--max-examples=50", "--phases=fuzzing", "--checks=not_a_server_error"
    )

    pytester.makepyfile(test_regressions=path.read_text(encoding="utf-8"))
    pytester.runpytest().assert_outcomes(passed=1)


def test_default_report_is_collected_by_pytest(ctx, cli, tmp_path, pytester):
    api = ctx.openapi.apps.failure()
    cli.run_and_assert(
        api.schema_url,
        "--report=pytest",
        f"--report-dir={tmp_path}",
        "--max-examples=1",
        "--phases=fuzzing",
        "--checks=not_a_server_error",
        exit_code=ExitCode.TESTS_FAILED,
    )
    pytester.runpytest(str(tmp_path)).assert_outcomes(passed=1)


def test_credentials_are_sanitized(ctx, cli, tmp_path):
    api = ctx.openapi.apps.failure()
    path = tmp_path / "test_regressions.py"
    cli.run(
        api.schema_url,
        f"--report-pytest-path={path}",
        "--header=Authorization: Bearer secret-token",
        "--max-examples=1",
        "--phases=fuzzing",
        "--checks=not_a_server_error",
    )
    content = path.read_text(encoding="utf-8")
    assert ("secret-token" in content, "'Authorization': '[Filtered]'" in content) == (False, True)
