"""Failures of a run as a standalone pytest file."""

from __future__ import annotations

import re
from pathlib import Path
from typing import TYPE_CHECKING

from schemathesis.cli.commands.run.handlers.base import EventHandler
from schemathesis.cli.events import LoadingFinished
from schemathesis.core.failures import format_failures
from schemathesis.core.output.sanitization import sanitize_url, sanitize_value
from schemathesis.core.version import SCHEMATHESIS_VERSION
from schemathesis.engine.events import ScenarioFinished

if TYPE_CHECKING:
    from schemathesis.cli.context import BaseExecutionContext
    from schemathesis.config import OutputConfig
    from schemathesis.engine import events
    from schemathesis.engine.recorder import Interaction
    from schemathesis.engine.statistic import Statistic


def _render_request(interaction: Interaction, config: OutputConfig) -> list[str]:
    request = interaction.request
    headers = {name: ", ".join(values) for name, values in request.headers.items()}
    uri = request.uri
    if config.sanitization.enabled:
        uri = sanitize_url(uri, config=config.sanitization)
        sanitize_value(headers, config=config.sanitization)
    lines = ["    response = requests.request(", f"        {request.method!r},", f"        {uri!r},"]
    lines.append(f"        headers={headers!r},")
    if request.body is not None:
        lines.append(f"        data={request.body!r},")
    lines.append("    )")
    if interaction.response is None:
        lines.append("    # No response was received")
    else:
        lines.append(f"    assert response.status_code == {interaction.response.status_code}")
    return lines


def render(
    statistic: Statistic, interactions: dict[str, Interaction], config: OutputConfig, location: str | None
) -> str:
    lines = [f"# Generated by Schemathesis {SCHEMATHESIS_VERSION}" + (f" from {location}" if location else "")]
    lines.append("# Each test asserts the status code observed during the run, so it fails once the behavior changes.")
    if config.sanitization.enabled:
        lines.append(
            f"# Sensitive values are replaced with `{config.sanitization.replacement}`; fill them in before running."
        )
    lines.append("import requests")
    for label in sorted(statistic.failures):
        for index, group in enumerate(statistic.failures[label].values(), 1):
            if group.case_id is None:
                continue
            chain = [interactions[step.case_id] for step in group.steps if step.case_id in interactions]
            if not chain:
                continue
            explanation = format_failures(
                case_id=f"{index}. Test Case ID: {group.case_id}",
                response=group.response,
                failures=group.failures,
                curl=None,
                auth_identity=group.auth_identity,
                config=config,
            )
            slug = re.sub(r"\W+", "_", group.steps[-1].operation).strip("_").lower()
            lines.extend(["", "", f"# {label}"])
            # Every explanation line stays a comment, whatever the response body contains.
            lines.extend(f"# {line}" if line else "#" for line in explanation.splitlines())
            lines.append(f"def test_{slug}_{group.case_id}():")
            for interaction in chain:
                lines.extend(_render_request(interaction, config))
    return "\n".join(lines) + "\n"


class PytestReportHandler(EventHandler["BaseExecutionContext"]):
    """Keep the requests of failing scenarios and write them as pytest tests at shutdown."""

    __slots__ = ("output", "location", "interactions")

    def __init__(self, output: Path) -> None:
        self.output = output
        self.location: str | None = None
        self.interactions: dict[str, Interaction] = {}

    def handle_event(self, ctx: BaseExecutionContext, event: events.EngineEvent) -> None:
        if isinstance(event, LoadingFinished):
            self.location = event.location
        elif isinstance(event, ScenarioFinished):
            recorder = event.recorder
            for checks in recorder.checks.values():
                for check in checks:
                    if check.failure_info is None:
                        continue
                    for step in check.failure_info.steps:
                        interaction = recorder.interactions.get(step.case_id)
                        if interaction is not None:
                            self.interactions[step.case_id] = interaction

    def shutdown(self, ctx: BaseExecutionContext) -> None:
        self.output.parent.mkdir(parents=True, exist_ok=True)
        self.output.write_text(
            render(ctx.statistic, self.interactions, ctx.config.output, self.location), encoding="utf-8"
        )
